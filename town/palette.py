def light_at(hour):
    """返回某个时刻的 (叠加色, 强度)，在关键帧之间线性插值。"""
    hour = hour % 24.0
    for i in range(len(LIGHT_KEYS) - 1):
        h0, c0, s0 = LIGHT_KEYS[i]
        h1, c1, s1 = LIGHT_KEYS[i + 1]
        if h0 <= hour <= h1:
            t = 0.0 if h1 == h0 else (hour - h0) / (h1 - h0)
            return mix(c0, c1, t), s0 + (s1 - s0) * t
    return LIGHT_KEYS[0][1], LIGHT_KEYS[0][2]


def is_night(hour):
    """判断是否算夜里（用于开灯、出萤火虫）。"""
    return hour < 6.0 or hour >= 19.5
