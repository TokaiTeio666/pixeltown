def shade(rgb, factor):
    """按比例调亮(>1)或调暗(<1)一个颜色，带上下限保护。"""
    r, g, b = rgb
    return (
        max(0, min(255, int(r * factor))),
        max(0, min(255, int(g * factor))),
        max(0, min(255, int(b * factor))),
    )


def mix(a, b, t):
    """在两个颜色之间线性插值，t=0 返回 a，t=1 返回 b。"""
    t = max(0.0, min(1.0, t))
    return (
        int(a[0] + (b[0] - a[0]) * t),
        int(a[1] + (b[1] - a[1]) * t),
        int(a[2] + (b[2] - a[2]) * t),
    )


def c(name):
    """按名字取色。"""
    return PAL[name]


